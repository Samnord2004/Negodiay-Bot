#!/usr/bin/env bash
# =============================================================================
# Запуск портала Негодяев на macOS / Linux (на портах отличных от 3000 и 5000)
# Использование:
#   ./start-local.sh             (по умолчанию порт 8090)
#   ./start-local.sh 7777        (любой произвольный порт)
# =============================================================================

set -e

TARGET_PORT="${1:-8090}"

echo "============================================================="
echo "   🏴‍☠️ ПОРТАЛ НЕГОДЯЕВ: ЛОКАЛЬНЫЙ СЕРВЕР (macOS / Linux)     "
echo "============================================================="

# Проверка наличия Node.js
if ! command -v node &> /dev/null; then
    echo "❌ Ошибка: Node.js не найден. Установите Node.js (v18+ / v20+ / v22+) с https://nodejs.org"
    exit 1
fi

NODE_VER=$(node -v)
echo "✓ Node.js обнаружен: $NODE_VER"

# Установка зависимостей при необходимости
if [ ! -d "node_modules" ]; then
    echo "📦 Каталог node_modules не найден. Устанавливаем зависимости..."
    npm install
fi

# Сборка проекта при необходимости
if [ ! -f "dist/server.cjs" ] || [ ! -f "dist/index.html" ]; then
    echo "🔨 Сборка клиентского и серверного бандла..."
    npm run build
fi

echo ""
echo "🚀 Запуск приложения на порту: $TARGET_PORT"
echo "ℹ️  Порты 3000 (React dev) и 5000 (macOS AirPlay) НЕ используются!"
echo ""

# Запуск с передачей выбранного порта
exec node dist/server.cjs --port "$TARGET_PORT"
